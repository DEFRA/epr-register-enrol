/**
 * Parity OJ snapshot (READ-ONLY). Emits one JSONL line per application submitted to CM, then a trailer.
 *
 *   mongosh "<oj connection string incl. database>" --quiet oj-snapshot.js > oj.jsonl
 *
 * Optional: --eval "PARITY_DB='name'; undefined" to override the database, PARITY_COLLECTION for the collection.
 * Optional submission window on dateSent (updatedAt if dateSent is unset), half-open [start, end), ISO-8601
 * (UTC if no offset), either bound may be omitted:
 *   --eval "PARITY_START='2026-10-01T00:00:00Z'; PARITY_END='2026-11-01T00:00:00Z'; undefined"
 * Stdout carries ONLY JSONL (mongosh has no stderr), so there is no progress output. GENERATED by build.mjs - edit src/, not this file.
 */
const TARGET_DB = typeof PARITY_DB !== 'undefined' && PARITY_DB ? PARITY_DB : db.getName()
const COLLECTION = typeof PARITY_COLLECTION !== 'undefined' && PARITY_COLLECTION ? PARITY_COLLECTION : 'accreditationApplications'
const collection = db.getSiblingDB(TARGET_DB).getCollection(COLLECTION)
installReadOnlyGuard(collection, 'oj-snapshot')

const STATUS = ['Saved', 'Started', 'Submitted', 'DulyMade', 'Queried', 'Updated', 'AwaitingDecision', 'Approved', 'Rejected', 'Withdrawn']
const takenAt = new Date().toISOString()

function uuidStr(v) {
  if (v === undefined || v === null) return null
  if (typeof v.toUUID === 'function') return v.toUUID().toString().replace(/^UUID\("?|"?\)$/g, '')
  return idStr(v)
}
function oidStr(v) {
  if (v === undefined || v === null) return null
  return typeof v.toHexString === 'function' ? v.toHexString() : idStr(v)
}

// Reshape the OJ document into the payload BuildPayload sends, so the shared normaliser sees the same shape as CM.
// BuildPayload ALWAYS sends all four sections: Prns, BusinessPlan and SamplingPlan are non-null on the C# model
// (default instances) and OverseasSites is sent as `OverseasSites?.Sites ?? []`. So an OJ document with no such
// element still reaches CM as an empty section, and is projected the same way here. (Field-level C# defaults such as
// `isNewSite = true` are deliberately NOT applied: a raw null there is the RA-292 signal.)
// Port of AccreditationChargeCalculator (fees in whole pounds; keep in step with that class).
const TONNAGE_FEES_POUNDS = { UpTo500: 546, UpTo5000: 2184, UpTo10000: 3276, Over10000: 3965 }
const OVERSEAS_SITE_FEE_POUNDS = 328
function chargePence(band, selectedSites) {
  const fee = TONNAGE_FEES_POUNDS[band]
  return fee === undefined ? null : (fee + OVERSEAS_SITE_FEE_POUNDS * selectedSites) * 100
}
// Port of HttpCaseWorkingApiAdapter.ExtractPostcode: the last UK-postcode-shaped match, upper-cased.
function extractPostcode(address) {
  if (typeof address !== 'string' || address.trim() === '') return null
  const all = address.match(/[A-Z]{1,2}\d[A-Z\d]?\s*\d[A-Z]{2}/gi)
  return all ? all[all.length - 1].toUpperCase() : null
}

function toPayload(d) {
  const prns = d.prns || {}
  const sites = d.overseasSites && Array.isArray(d.overseasSites.sites) ? d.overseasSites.sites : []
  const selectedSites = sites.filter((s) => s.selected === true)
  return {
    applicationReference: d.applicationReference,
    organisationName: d.organisationName,
    operatorOrgNumber: d.orgId,
    registrationNumber: d.registrationReference,
    glassRecyclingProcess: d.glassRecyclingProcess,
    wasteProcessingType: d.wasteProcessingType,
    chargeAmountPence: chargePence(enumName(prns.plannedTonnageBand, TONNAGE_BANDS), selectedSites.length),
    companiesHouseNumber: d.companiesHouseNumber,
    companyRegisteredAddress: d.companyRegisteredAddress,
    siteAddress: d.siteAddress,
    siteAddressPostcode: extractPostcode(d.siteAddress),
    permitNumbers: d.permitNumbers,
    submitterContactDetails: d.submitterContactDetails,
    businessPlan: d.businessPlan || {},
    prns: { plannedTonnageBand: prns.plannedTonnageBand, authorisers: Array.isArray(prns.authorisers) ? prns.authorisers : [] },
    samplingPlan: {
      files: d.samplingPlan && Array.isArray(d.samplingPlan.files) ? d.samplingPlan.files : []
    },
    overseasSites: {
      sites: selectedSites
        .map((s) =>
          Object.assign({}, s, {
            besEvidence: { files: (s.besEvidence && s.besEvidence.besEvidenceUploads) || [] }
          })
        )
    }
  }
}

const win = parseWindow(
  typeof PARITY_START !== 'undefined' ? PARITY_START : null,
  typeof PARITY_END !== 'undefined' ? PARITY_END : null
)
const submitted = {
  $or: [{ caseManagementWorkItemId: { $ne: null } }, { applicationStatus: { $nin: ['Saved', 'Started'] } }]
}
// The window applies to the submission time (dateSent), falling back to updatedAt where dateSent was never set.
const sent = rangeClause('dateSent', win)
const updated = rangeClause('updatedAt', win)
const filter = sent
  ? { $and: [submitted, { $or: [sent, { $and: [{ dateSent: null }, updated] }] }] }
  : submitted
let count = 0
const cursor = collection.find(filter).readPref('secondaryPreferred').batchSize(500)
while (cursor.hasNext()) {
  const d = cursor.next()
  const status = enumName(d.applicationStatus, STATUS)
  const record = {
    snapshot: { service: 'OJ', takenAt, db: TARGET_DB, scriptVersion: SCRIPT_VERSION },
    key: { applicationId: oidStr(d._id), workItemId: uuidStr(d.caseManagementWorkItemId) },
    identity: {
      applicationReference: nz(d.applicationReference),
      registrationNumber: nz(d.registrationReference),
      accreditationNumber: nz(d.accreditationReference),
      organisationName: nz(d.organisationName),
      orgNumber: nz(d.orgId),
      material: nz(d.materialType) === null ? null : String(enumName(d.materialType, [])).toLowerCase(),
      year: nz(d.year),
      isExporter: nz(d.isExporter)
    },
    state: { raw: status, normalised: status, updatedAt: iso(d.updatedAt) },
    sections: normaliseSections(toPayload(d))
  }
  print(JSON.stringify(record))
  count++
}
print(JSON.stringify({
  trailer: true, service: 'OJ', count, takenAt, scriptVersion: SCRIPT_VERSION,
  window: { start: iso(win.start), end: iso(win.end) }
}))
